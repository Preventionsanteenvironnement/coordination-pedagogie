import assert from 'node:assert/strict';
import {plagesVides, fondPlages} from '../plages-vides.mjs';
const o=(debut,fin,extra={})=>({j:0,debut,fin,type:'cours',...extra});
assert.deepEqual(plagesVides([],[],0),[{debut:480,fin:1080,etat:'vide'}]);
assert.deepEqual(plagesVides([o('09:00','12:00'),o('13:00','14:00',{type:'reunion'}),o('12:30','13:00',{type:'service'})],[],0),[{debut:480,fin:540,etat:'vide'},{debut:720,fin:750,etat:'vide'},{debut:840,fin:1080,etat:'vide'}]);
assert.equal(plagesVides([],[o('08:00','18:00',{type:'repos'})],0)[0].etat,'off');
assert.equal(plagesVides([],[o('08:00','18:00',{type:'repos',sem:'A'})],0)[0].etat,'vide');
assert.deepEqual(plagesVides([o('08:00','12:00',{sem:'A'}),o('12:00','18:00',{sem:'B'})],[],0),[]);
assert.deepEqual(plagesVides([o('17:00','21:00',{type:'service'})],[],0),[{debut:480,fin:1020,etat:'vide'}]);
assert.equal(plagesVides([o('09:00','10:00',{pole:'MDA'})],[],0).length,2);
assert(!fondPlages([],[],0,1.25).includes('data-a='));
